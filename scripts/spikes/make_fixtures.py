def trim_table(tbl):
    data = tbl.get("data")
    if not isinstance(data, list) or len(data) <= MAXROWS:
        return tbl
    keep = list(data[:20])
    seen = set()
    for row in data[20:]:
        cells = [str(c) for c in row]
        sig = []
        for c in cells:
            m = SIGN_CELL.fullmatch(c.strip())
            if m:
                sig.append("sign:" + m.group(1).strip())
            if c.strip() in ("--", "0.00", "-", "----", "---", "除息", "除權", "除權息"):
                sig.append("cell:" + c.strip())
        new = [s for s in sig if s not in seen]
        if new and len(keep) < MAXROWS:
            keep.append(row)
            seen.update(sig)
    out = dict(tbl)
    out["data"] = keep[:MAXROWS]
    if "totalCount" in out:
        out["totalCount"] = len(out["data"])
    return out


def trim(obj):
    if isinstance(obj, dict):
        obj = dict(obj)
        if "tables" in obj and isinstance(obj["tables"], list):
            obj["tables"] = [trim_table(t) if isinstance(t, dict) else t for t in obj["tables"]]
        elif "data" in obj:
            obj = trim_table(obj)
    return obj


def write(rel, text):
    p = OUT / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, encoding="utf-8")


def synthetic(rel, status, body, headers=None):
    write(
        rel,
        json.dumps(
            {"status": status, "headers": headers or {}, "body": body}, ensure_ascii=False, indent=1
        ),
    )


